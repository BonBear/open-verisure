#!/usr/bin/env python3
"""
derive_key.py - Verisure Sensor Key Derivation (KDF) & Config Generator

Derives a unique 128-bit AES Device Key from a 16-byte Master Key and
the physical Device ID printed on the sensor's casing (e.g. "2JHL 2MVN").

============================================================================
KDF MATHEMATICAL SPECIFICATION:
============================================================================
Formula:
    Device_Key = AES-128_ECB(Master_Key, Pad16(Device_ID))

Input:
    - Master_Key : 16 bytes (128 bits) hex string or environment variable.
    - Device_ID  : 8 ASCII characters (alphanumeric, spaces and hyphens stripped).
    - Pad16(ID)  : 8-byte ID right-padded with 8 zero bytes (0x00) to 16 bytes.

Output:
    - Device_Key : 16 bytes (128 bits) AES key in hexadecimal or C-array format.

Usage Examples:
    # 1. Derive key for a device ID and print to console:
    python derive_key.py --id "2JHL 2MVN"

    # 2. Derive key and automatically write to VerisureDoorSensor/config.h:
    python derive_key.py --id "2JHL 2MVN" --write-config

    # 3. Use custom master key:
    python derive_key.py --id "2JHL 2MVN" --master-key "00112233445566778899AABBCCDDEEFF"

    # 4. Generate a new secure random 128-bit Master Key:
    python derive_key.py --generate-master
============================================================================
"""

import os
import sys
import re
import argparse
import secrets
from typing import Optional
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.backends import default_backend

# Default Development Master Key (16 bytes / 128 bits)
DEFAULT_MASTER_KEY_HEX = "0102030405060708090A0B0C0D0E0F10"
CONFIG_H_PATH = os.path.join(os.path.dirname(__file__), "VerisureDoorSensor", "config.h")
SECRETS_H_PATH = os.path.join(os.path.dirname(__file__), "868Receiver", "src", "secrets.h")


def get_master_key_from_secrets() -> Optional[str]:
    """
    Parse MASTER_KEY_HEX, MASTER_AES_KEY_HEX, or DEFAULT_MASTER_KEY_HEX from
    868Receiver/src/secrets.h if the file exists.

    Returns:
        Optional[str]: 32-character hex key string or None.
    """
    if os.path.isfile(SECRETS_H_PATH):
        try:
            with open(SECRETS_H_PATH, "r", encoding="utf-8") as f:
                content = f.read()
                match = re.search(r'#define\s+(?:MASTER_KEY_HEX|MASTER_AES_KEY_HEX|DEFAULT_MASTER_KEY_HEX)\s+"([0-9a-fA-F]{32})"', content)
                if match:
                    return match.group(1).upper()
        except Exception:
            pass
    return None


def clean_device_id(raw_id: str) -> str:
    """
    Normalize device ID to 8 uppercase alphanumeric characters.

    Args:
        raw_id (str): Raw input string (e.g. "2JHL 2MVN" or "vs-mag01").

    Returns:
        str: 8-character uppercase identifier.
    """
    clean = raw_id.strip().replace(" ", "").replace("-", "").upper()
    if len(clean) > 8:
        clean = clean[:8]
    elif len(clean) < 8:
        clean = clean.ljust(8, "_")
    return clean


def derive_device_key(master_key_bytes: bytes, device_id: str) -> bytes:
    """
    Derive 16-byte Device Key = AES_ECB(Master_Key, Pad16(Device_ID)).

    Args:
        master_key_bytes (bytes): Exactly 16 bytes master key.
        device_id (str): Cleaned 8-character device ID.

    Returns:
        bytes: 16-byte derived encryption key.
    """
    if len(master_key_bytes) != 16:
        raise ValueError(f"Master key must be exactly 16 bytes (got {len(master_key_bytes)}).")

    # Pad 8-byte device ID to 16 bytes with zeros
    padded_id = device_id.encode("ascii").ljust(16, b"\x00")

    cipher = Cipher(algorithms.AES(master_key_bytes), modes.ECB(), backend=default_backend())
    encryptor = cipher.encryptor()
    return encryptor.update(padded_id) + encryptor.finalize()


def format_c_array(key_bytes: bytes) -> str:
    """Format 16 bytes as a C array literal for header files."""
    chunk1 = ", ".join(f"0x{b:02X}" for b in key_bytes[:8])
    chunk2 = ", ".join(f"0x{b:02X}" for b in key_bytes[8:])
    return f"    {chunk1},\n    {chunk2}"


def write_config_header(device_id: str, device_key: bytes, output_path: str):
    """
    Generate and write VerisureDoorSensor/config.h file.

    Args:
        device_id (str): 8-character device ID.
        device_key (bytes): 16-byte device encryption key.
        output_path (str): Target filesystem destination path.
    """
    c_bytes = format_c_array(device_key)
    content = f"""/**
 * @file config.h
 * @brief Auto-generated Verisure Sensor Node Configuration
 * Generated by derive_key.py for Device ID: {device_id}
 */

#ifndef CONFIG_H
#define CONFIG_H

#include <stdint.h>

#define DEVICE_ID "{device_id}"

static const __code uint8_t DEVICE_AES_KEY[16] = {{
{c_bytes}
}};

#endif // CONFIG_H
"""
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[+] Wrote configuration to: {output_path}")


def main():
    parser = argparse.ArgumentParser(
        description="Verisure Sensor Key Derivation Tool (AES-128 KDF)",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__
    )
    parser.add_argument("--id", "-i", help="Physical Device ID (e.g. '2JHL 2MVN' or '2JHL2MVN')")
    parser.add_argument("--master-key", "-m", default=None,
                        help="16-byte Master Key in hex (32 hex characters). Default: env or built-in.")
    parser.add_argument("--generate-master", action="store_true", help="Generate a random 128-bit master key")
    parser.add_argument("--write-config", "-w", action="store_true",
                        help=f"Write output directly to {CONFIG_H_PATH}")

    args = parser.parse_args()

    if args.generate_master:
        new_master = secrets.token_hex(16).upper()
        print("[+] Generated Random 128-Bit Master Key (Hex):")
        print(f"    {new_master}")
        print("\nSave this key securely! It will be used by the ESP32 receiver to decrypt all your devices.")
        return

    if not args.id:
        parser.error("Argument --id is required (e.g. --id '2JHL 2MVN').")

    # Resolve Master Key in order of precedence:
    # 1. Explicit CLI argument (--master-key)
    # 2. Environment variable (VERISURE_MASTER_KEY)
    # 3. Compile-time configuration in 868Receiver/src/secrets.h
    # 4. Built-in development fallback
    key_source = ""
    if args.master_key:
        master_hex = args.master_key
        key_source = "CLI argument (--master-key)"
    elif os.environ.get("VERISURE_MASTER_KEY"):
        master_hex = os.environ.get("VERISURE_MASTER_KEY")
        key_source = "Environment variable (VERISURE_MASTER_KEY)"
    else:
        secrets_key = get_master_key_from_secrets()
        if secrets_key:
            master_hex = secrets_key
            key_source = "868Receiver/src/secrets.h"
        else:
            master_hex = DEFAULT_MASTER_KEY_HEX
            key_source = "Built-in fallback default"

    try:
        master_bytes = bytes.fromhex(master_hex.strip())
    except ValueError:
        print(f"[-] Error: Master key must be valid hex (got: '{master_hex}').")
        sys.exit(1)

    device_id = clean_device_id(args.id)
    device_key = derive_device_key(master_bytes, device_id)

    print("=" * 65)
    print("  VERISURE SENSOR KEY DERIVATION (KDF)")
    print("=" * 65)
    print(f"[*] Input Device ID : {args.id}")
    print(f"[*] Clean Device ID : {device_id} (8 ASCII bytes)")
    print(f"[*] Master Key (Hex): {master_bytes.hex().upper()}")
    print(f"[*] Key Source      : {key_source}")
    print(f"[+] Device Key (Hex): {device_key.hex().upper()}")
    print("-" * 65)
    print("C Array Format:")
    print("static const __code uint8_t DEVICE_AES_KEY[16] = {")
    print(format_c_array(device_key))
    print("};")
    print("=" * 65)

    if args.write_config:
        write_config_header(device_id, device_key, CONFIG_H_PATH)


if __name__ == "__main__":
    main()
