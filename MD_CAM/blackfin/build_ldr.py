#!/usr/bin/env python3
"""
build_ldr.py - Build a Blackfin assembly/C program for the ADSP-BF512 and turn it into
an LDR boot stream plus a C header that the CC1110 firmware sends over SPI0 slave boot.

Usage:
    python build_ldr.py [source ...]       (default: spi_probe.S)
    python build_ldr.py --elf-only source  (ELF for JTAG loading, no LDR/header)

Output:
    build/<name>.elf, build/<name>.ldr
    ../firmware/bf_ldr.h  (const __code uint8_t bf_ldr[] = {...})
"""
import os
import struct
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
# Windows: the ADI toolchain in C:\Tools; elsewhere BFIN_TOOLCHAIN, or bfin-elf-* on PATH.
EXE = ".exe" if os.name == "nt" else ""
TOOLCHAIN = os.environ.get("BFIN_TOOLCHAIN", r"C:\Tools\adi-blackfin\elf\bin" if os.name == "nt" else "")
GCC = os.path.join(TOOLCHAIN, "bfin-elf-gcc" + EXE)
LDR = os.path.join(TOOLCHAIN, "bfin-elf-ldr" + EXE)
BUILD = os.path.join(HERE, "build")
HEADER = os.path.join(HERE, "..", "firmware", "bf_ldr.h")

BFLAG_FINAL, BFLAG_FIRST, BFLAG_IGNORE, BFLAG_INIT, BFLAG_FILL = 0x8000, 0x4000, 0x1000, 0x0800, 0x0100


def run(cmd):
    res = subprocess.run(cmd, cwd=HERE, capture_output=True, text=True)
    if res.returncode != 0:
        sys.exit(f"[-] {' '.join(cmd)}\n{res.stdout}{res.stderr}")
    return res.stdout


def check_ldr(data: bytes) -> None:
    """Walk the BF51x block headers: signature 0xAD, XOR of the 16 header bytes must be 0."""
    off = 0
    while off < len(data):
        hdr = data[off:off + 16]
        if len(hdr) < 16:
            sys.exit(f"[-] Truncated header at {off:#x}")
        code, addr, count, arg = struct.unpack("<IIII", hdr)
        x = 0
        for b in hdr:
            x ^= b
        flags = code & 0xFFFF
        names = [n for n, f in (("FINAL", BFLAG_FINAL), ("FIRST", BFLAG_FIRST), ("IGNORE", BFLAG_IGNORE),
                                ("INIT", BFLAG_INIT), ("FILL", BFLAG_FILL)) if flags & f]
        print(f"    block @{off:#06x} code={code:08x} addr={addr:08x} count={count:#x} arg={arg:#x} "
              f"dma={code & 0xF} {'|'.join(names) or '-'} {'OK' if (code >> 24) == 0xAD and x == 0 else 'BAD'}")
        if (code >> 24) != 0xAD or x != 0:
            sys.exit("[-] Bad block header")
        off += 16 + (0 if flags & BFLAG_FILL else count)
        if flags & BFLAG_FINAL:
            break
    if off != len(data):
        print(f"[!] {len(data) - off} trailing bytes after FINAL block")


def write_header(name: str, data: bytes) -> None:
    lines = [
        "/* Generated by MD_CAM/blackfin/build_ldr.py - do not edit. */",
        f"/* Blackfin LDR boot stream from {name} ({len(data)} bytes). */",
        "#ifndef BF_LDR_H",
        "#define BF_LDR_H",
        "",
        f"#define BF_LDR_LEN {len(data)}",
        "static const __code uint8_t bf_ldr[BF_LDR_LEN] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 16]) + ",")
    lines += ["};", "", "#endif", ""]
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main() -> None:
    args = sys.argv[1:]
    elf_only = "--elf-only" in args
    header = "--header" in args          # also write firmware/bf_ldr.h (CC1110 SPI boot test)
    sources = [a for a in args if a not in ("--elf-only", "--header")] or ["spi_probe.S"]
    name = os.path.splitext(os.path.basename(sources[0]))[0]
    os.makedirs(BUILD, exist_ok=True)
    elf = os.path.join(BUILD, name + ".elf")
    ldr = os.path.join(BUILD, name + ".ldr")

    run([GCC, "-mcpu=bf512-0.2", "-O2", "-nostdlib", "-nostartfiles", "-Wl,-T,bf512_l1.ld", "-o", elf] + sources)
    print(f"[+] {elf}")
    if elf_only:
        return
    if os.path.exists(ldr):
        os.remove(ldr)
    run([LDR, "-T", "BF518", "-c", "-d", "1", ldr, elf])

    data = open(ldr, "rb").read()
    print(f"[+] {ldr} ({len(data)} bytes)")
    check_ldr(data)
    if header:
        write_header(os.path.basename(sources[0]), data)
        print(f"[+] {os.path.normpath(HEADER)}")


if __name__ == "__main__":
    main()
